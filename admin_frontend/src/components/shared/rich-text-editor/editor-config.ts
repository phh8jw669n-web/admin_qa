export type RichTextEditorVariant = 'full' | 'compact'

export function createEditorConfig(
  variant: RichTextEditorVariant,
  placeholder: string,
): EditorConfig {
  return {
    licenseKey: 'GPL',
    placeholder,
    plugins: [
      Essentials,
      Paragraph,
      Autoformat,
      Bold,
      Italic,
      Underline,
      Strikethrough,
      Subscript,
      Superscript,
      RemoveFormat,
      List,
      Indent,
      IndentBlock,
      BlockQuote,
      Link,
      AutoLink,
      Image,
      ImageCaption,
      ImageInsert,
      ImageResize,
      ImageStyle,
      ImageToolbar,
      ImageUpload,
      AutoImage,
      PictureEditing,
      LinkImage,
      EditorImageUpload,
      MediaEmbed,
      AutoMediaEmbed,
      Table,
      TableToolbar,
      TableCaption,
      TableProperties,
      TableCellProperties,
      TableColumnResize,
      HorizontalLine,
      SpecialCharacters,
      SpecialCharactersEssentials,
      SourceEditing,
      PasteFromOffice,
      GeneralHtmlSupport,
      WordCount,
      EditorExtras,
    ],
    toolbar: {
      items: [...(variant === 'compact' ? COMPACT_TOOLBAR : FULL_TOOLBAR)],
      shouldNotGroupWhenFull: true,
    },
    link: {
      defaultProtocol: 'https://',
      decorators: {
        openInNewTab: {
          mode: 'manual',
          label: 'Open in a new tab',
          attributes: {
            target: '_blank',
            rel: 'noopener noreferrer',
          },
        },
      },
    },
    image: {
      toolbar: [
        'imageTextAlternative',
        'toggleImageCaption',
        'imageStyle:inline',
        'imageStyle:block',
        'imageStyle:side',
        'resizeImage',
      ],
      insert: {
        integrations: ['upload', 'url'],
      },
    },
    table: {
      contentToolbar: [
        'tableColumn',
        'tableRow',
        'mergeTableCells',
        'tableProperties',
        'tableCellProperties',
      ],
    },
    htmlSupport: {
      allow: [
        {
          name: 'span',
          classes: ['math-tex'],
        },
      ],
    },
  }
}

